@dp.message(Form.waiting_for_user_ball)
async def c3(m: types.Message, state: FSMContext):
    if not m.text.isdigit(): return await m.answer("Только цифры!")
    d = await state.get_data()
    mx = d['mx']
    us = int(m.text)
    if us > mx:
        await state.clear()
        return await m.answer("Ой! Твой балл больше максимального. Давай заново.")
    p = (us/mx)*100
    if p>=85: g, msg = "5", "Превосходная работа!"
    elif p>=65: g, msg = "4", "Ты молодец, хороший результат!"
    elif p>=40: g, msg = "3", "Нормально, но ты можешь лучше."
    else: g, msg = "2", "Всё получится, не опускай руки!"
    await m.answer(f"📊 Результат: {us}/{mx} ({round(p,1)}%)\nС большей вероятностью Ваша оценка — {g}\n\n{msg}"); await state.clear()

